#!/usr/bin/env node
/**
 * gen-globals.mjs — derive the list of top-level declarations from the legacy app.
 *
 * WHY GENERATE INSTEAD OF HAND-WRITING
 * ------------------------------------
 * The module bridge (app/core/module-bridge.ts) has to publish the legacy app's
 * top-level bindings on `globalThis`, because a classic <script>'s `var`s are
 * globals while an ES module's are module-private. That is ~830 names and the
 * list changes whenever anyone adds a function — a hand-maintained copy would
 * rot silently and produce "undefined is not a function" at runtime.
 *
 * So we parse the real source and emit the list. `--check` fails if the
 * committed list is stale, which makes drift a build error rather than a
 * runtime mystery.
 *
 * Parsing note: a naive `grep '^var (\w+)'` misses multi-name declarations such
 * as `var bodies=[],freeG=[],parts=[];` (src/10-app.js:52) and would also pick
 * up names inside comments. We scan line by line, skip comment-only lines, and
 * split multi-name `var` statements on top-level commas.
 *
 * Run: node tools/gen-globals.mjs
 *      node tools/gen-globals.mjs --check
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src', '10-app.js');
const OUT = join(ROOT, 'app', 'core', 'legacy-globals.generated.ts');
const CHECK = process.argv.includes('--check');

const lines = readFileSync(SRC, 'utf8').split('\n');
const names = new Set();

/** Strip a trailing `//` comment that is not inside a string. */
function stripLineComment(s) {
  let inS = null;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (inS) {
      if (c === '\\') i++;
      else if (c === inS) inS = null;
    } else if (c === '"' || c === "'" || c === '`') inS = c;
    else if (c === '/' && s[i + 1] === '/') return s.slice(0, i);
  }
  return s;
}

/** Split a `var` declaration list on commas that are at bracket depth 0. */
function splitTopLevel(s) {
  const out = [];
  let depth = 0, inS = null, cur = '';
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (inS) {
      cur += c;
      if (c === '\\') { cur += s[++i] ?? ''; continue; }
      if (c === inS) inS = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') { inS = c; cur += c; continue; }
    if ('([{'.includes(c)) depth++;
    else if (')]}'.includes(c)) depth--;
    else if (c === ',' && depth === 0) { out.push(cur); cur = ''; continue; }
    cur += c;
  }
  if (cur.trim()) out.push(cur);
  return out;
}

for (const raw of lines) {
  const line = stripLineComment(raw).trim();
  if (!line || line.startsWith('/*') || line.startsWith('*')) continue;

  // function NAME(...)  — cannot contain top-level commas before the name
  let m = line.match(/^function\s+([A-Za-z_$][\w$]*)/);
  if (m) { names.add(m[1]); continue; }

  // var a=1,b=2;  — only top-level (column 0) declarations
  if (/^var\s/.test(line) && raw.startsWith('var')) {
    const decl = line.replace(/^var\s+/, '').replace(/;\s*$/, '');
    for (const part of splitTopLevel(decl)) {
      const nm = part.trim().match(/^([A-Za-z_$][\w$]*)/);
      if (nm) names.add(nm[1]);
    }
  }
}

const sorted = [...names].sort();

// Sanity floor: if parsing silently breaks we would emit a tiny list and the
// app would boot with almost nothing published. Fail loudly instead.
if (sorted.length < 700) {
  console.error(`gen-globals: only parsed ${sorted.length} declarations — expected 700+. ` +
    `The parser probably broke; refusing to emit a truncated list.`);
  process.exit(1);
}

const content = `/**
 * GENERATED by tools/gen-globals.mjs — do not edit by hand.
 *
 * Every top-level declaration in the legacy app (src/10-app.js).
 * Source of truth: that file. Regenerate with: node tools/gen-globals.mjs
 *
 * These names are republished on globalThis by app/core/module-bridge.ts, so
 * that switching the app from a classic <script> to an ES module does not break
 * the replay harness, the boss script, or the in-page recorder — all of which
 * reach for bare globals.
 *
 * This file goes away in phase C, when subsystems are migrated to real imports.
 */
export const LEGACY_GLOBAL_NAMES = [
${sorted.map((n) => `  '${n}',`).join('\n')}
] as const;

/** Count of declarations, for diagnostics and the sanity check in tests. */
export const LEGACY_GLOBAL_COUNT = ${sorted.length};
`;

if (CHECK) {
  const existing = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (existing !== content) {
    console.error('gen-globals --check: legacy-globals.generated.ts is STALE');
    console.error('  run: node tools/gen-globals.mjs');
    process.exit(1);
  }
  console.log(`gen-globals --check: OK — ${sorted.length} declarations, list is fresh`);
} else {
  writeFileSync(OUT, content);
  console.log(`gen-globals: wrote ${sorted.length} declarations to app/core/legacy-globals.generated.ts`);
  const fns = [...names].filter((n) => new RegExp(`^function ${n}\\b`, 'm').test(readFileSync(SRC, 'utf8'))).length;
  console.log(`  (${fns} functions, ${sorted.length - fns} vars)`);
}
