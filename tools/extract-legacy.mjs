#!/usr/bin/env node
/**
 * extract-legacy.mjs — generate the Vite app's assets from the legacy fragments.
 *
 * WHY THIS EXISTS
 * ---------------
 * During the migration there must be exactly ONE source of truth for the page
 * markup and CSS, or the two builds will silently drift and the replay net will
 * stop meaning anything.
 *
 * The legacy layout is:
 *   src/00-head.html   <!DOCTYPE> … <style>…</style>     (ends at </style>)
 *   src/05-body.html   the static DOM, up to the first <script>
 *   src/vendor/matter.js
 *   src/10-app.js
 *   src/50-mid.html    small DOM fragment between the two scripts
 *   src/90-boss.js
 *   src/99-tail.html
 *
 * This script splits those into what a real web build wants:
 *   app/legacy/style.css   the contents of <style>
 *   app/legacy/body.html   the static DOM (injected into #app-root at boot)
 *   app/legacy/mid.html    the mid fragment
 *
 * The JS parts are NOT copied — app/main.ts imports src/10-app.js and
 * src/90-boss.js directly, so there is no duplicate copy of the 20k-line file.
 *
 * Run: node tools/extract-legacy.mjs
 *      node tools/extract-legacy.mjs --check   (verify generated files are fresh)
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'app', 'legacy');
const CHECK = process.argv.includes('--check');

const head = readFileSync(join(SRC, '00-head.html'), 'utf8');
const body = readFileSync(join(SRC, '05-body.html'), 'utf8');
const mid = readFileSync(join(SRC, '50-mid.html'), 'utf8');

/** Pull the contents of the single <style> block out of the head fragment. */
function extractStyle(html) {
  const m = html.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
  if (!m) throw new Error('extract-legacy: no <style> block found in 00-head.html');
  return m[1];
}

/**
 * The static DOM: everything in 05-body.html. It contains no <script> tags
 * (verified: `grep -c '<script' src/05-body.html` == 0), so it can be injected
 * wholesale.
 */
function extractBody(html) {
  if (/<script/i.test(html)) {
    throw new Error('extract-legacy: 05-body.html unexpectedly contains a <script> tag; ' +
      'the injection strategy assumes it does not.');
  }
  return html;
}

const files = {
  'style.css': `/* GENERATED by tools/extract-legacy.mjs — do not edit.\n` +
               `   Source of truth: src/00-head.html (the <style> block). */\n` +
               extractStyle(head),
  'body.html': `<!-- GENERATED by tools/extract-legacy.mjs — do not edit.\n` +
               `     Source of truth: src/05-body.html -->\n` +
               extractBody(body),
  'mid.html': `<!-- GENERATED by tools/extract-legacy.mjs — do not edit.\n` +
              `     Source of truth: src/50-mid.html -->\n` +
              mid,
};

if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });

let stale = 0;
for (const [name, content] of Object.entries(files)) {
  const p = join(OUT, name);
  const existing = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (CHECK) {
    if (existing !== content) {
      console.error(`extract-legacy --check: ${name} is STALE (run: node tools/extract-legacy.mjs)`);
      stale++;
    }
  } else {
    writeFileSync(p, content);
    console.log(`wrote app/legacy/${name} (${content.length} bytes)`);
  }
}

if (CHECK) {
  if (stale) process.exit(1);
  console.log('extract-legacy --check: OK — app/legacy/ matches src/');
}
